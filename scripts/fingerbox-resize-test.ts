import { strict as assert } from 'node:assert';
import { isDefaultDistribution, resizeDistribution } from '../src/generators/fingerbox-resize';
assert.deepEqual(resizeDistribution('50mm:2', 2, 3), { text: '50mm:2:1', removed: [] });
assert.deepEqual(resizeDistribution('50mm:2:1', 3, 2), { text: '50mm:2', removed: [] });
assert.deepEqual(resizeDistribution('50mm:2:1', 3, 1), { text: '50mm', removed: ['2'] });
assert.deepEqual(resizeDistribution('33mm:50mm*2:1', 3, 1), { text: '33mm', removed: ['50mm*2'] });
assert.equal(resizeDistribution('1:', 2, 3), null);
assert.equal(resizeDistribution('1:2:3', 2, 3), null);
assert.equal(resizeDistribution('', 2, 3), null);
assert.equal(isDefaultDistribution('1:1:1', 3), true);
assert.equal(isDefaultDistribution(' 1 : 1 :1 ', 3), true);
assert.equal(isDefaultDistribution('1:1:1', 2), false);
assert.equal(isDefaultDistribution('1:2:1', 3), false);
assert.equal(isDefaultDistribution('3mm:1', 2), false);
assert.equal(isDefaultDistribution('1:1:', 3), false);
assert.equal(isDefaultDistribution('', 1), false);
assert.equal(isDefaultDistribution('1', 0), false);
assert.equal(isDefaultDistribution('1', 21), false);
console.log('ok   Fingerbox: ampliar o reducir distribuciones');