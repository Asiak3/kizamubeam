import './core-fixtures-env';
import { strict as assert } from 'node:assert';
import { EditorGenerators } from '../src/editor/generators';
import { buildGen, defaultParams, getGenerator } from '../src/generators/index';
import { cloneObjs, defaultImageLayer, defaultLayer, loadDoc, leaves } from '../src/model';
import type { Obj } from '../src/model';
const gen = getGenerator('box-divided')!;
const p = { ...defaultParams(gen), width: 300, depth: 200, height: 100, thickness: 6, finger: 20, compartmentsX: 3, compartmentsY: 2, ratiosX: '33mm:50mm*2:1', ratiosY: '1:1', dividerDrop: 10 };
const ed = Object.create(EditorGenerators.prototype);
ed.doc = loadDoc({ bed: { w: 2000, h: 2000 }, objs: [], layers: {} });
ed.currentLayer = 0; ed.agentCall = true; ed.sel = [];
ed.snapshot = () => {}; ed.touch = () => {}; ed.emit = () => {}; ed.setSel = (objects: Obj[]) => ed.sel = objects;
ed.layer = (i: number) => ed.doc.layers[i] ?? (ed.doc.layers[i] = defaultLayer(i));
const result = buildGen(gen, p), roots: Obj[] = ed.addGen(result, 0, { x: 300, y: 300 });
assert.equal(roots.length, 8);
assert.ok(roots.every(o => o.shape.kind === 'gen' && o.layer === 0));
const bottom = roots.find(o => o.shape.kind === 'gen' && o.shape.part === 'bottom')!;
assert.equal(bottom.shape.kind, 'gen');
if (bottom.shape.kind !== 'gen') throw Error('bottom');
assert.ok(bottom.shape.subs.length > 1, 'Holes remain as subpaths of the same piece');
const { buildJob, newDevice } = await import('../src/gcode');
const job = await buildJob({ doc: ed.doc, only: [bottom], layer: (i: number) => ({ ...defaultLayer(i), mode: 'line' as const, kerf: 0 }), imgLayer: () => defaultImageLayer(), device: { ...newDevice({ fw: 'fluidnc' }), startFrom: 'absolute' as const, optimize: false, returnHome: false } });
const expectedDistance = bottom.shape.subs.reduce((sum, sub) => sum + sub.nodes.reduce((d, q, i) => {
  const next = sub.nodes[(i + 1) % sub.nodes.length];
  return d + Math.hypot(next.x - q.x, next.y - q.y);
}, 0), 0);
let distance = 0, x = job.moves.x0, y = job.moves.y0;
for (let i = 0; i < job.moves.n; i++) {
  if (job.moves.f[i] > 0 && job.moves.s[i] > 0) distance += Math.hypot(job.moves.x[i] - x, job.moves.y[i] - y);
  x = job.moves.x[i]; y = job.moves.y[i];
}
assert.ok(Math.abs(distance - expectedDistance) < 0.01, `Nominal paths: ${distance} vs ${expectedDistance}`);
const copied = cloneObjs(roots);
assert.equal(copied.length, roots.length);
assert.notEqual((copied[0].shape as any).asm, (roots[0].shape as any).asm);
const saved = loadDoc(JSON.parse(JSON.stringify(ed.doc)));
const savedBottom = [...leaves(saved.objs)].map(([o]) => o).find(o => o.shape.kind === 'gen' && o.shape.part === 'bottom')!;
assert.equal(savedBottom.shape.kind, 'gen');
if (savedBottom.shape.kind !== 'gen') throw Error('saved bottom');
assert.deepEqual(savedBottom.shape.params.ratiosX, p.ratiosX);
assert.deepEqual(savedBottom.shape.subs, bottom.shape.subs);
const next = buildGen(gen, { ...p, top: 'closed', compartmentsX: 2, ratiosX: '33mm:1' });
ed.updateGen(bottom, next);
assert.equal(ed.doc.objs.length, 8);
assert.ok(ed.doc.objs.every((o: Obj) => o.shape.kind === 'gen' && o.layer === 0));
const updatedBottom = ed.doc.objs.find((o: Obj) => o.shape.kind === 'gen' && o.shape.part === 'bottom')!;
assert.equal(updatedBottom.shape.params.ratiosX, '33mm:1');
assert.ok(updatedBottom.shape.subs.length > 1);
const { collectScene } = await import('../src/view3d/panel');
const scene = collectScene(ed, 6, false).scene;
assert.equal(scene.solids.length, 8);
console.log('ok   Box mit Trennwänden: separate parts, holes, copy, save, edit and 3D');
