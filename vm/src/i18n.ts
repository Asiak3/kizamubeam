export function t(de: string, vars?: Record<string, string | number>): string {
  let s = lang === 'en' ? (EN[de] ?? de) : de;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
